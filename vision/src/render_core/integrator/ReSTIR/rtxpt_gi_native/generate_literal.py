"""Regenerate the GI-only literal using only the checked-in native sources.

Whole model files retain all source bytes except include directives. Helper
excerpts retain their exact function/type bodies. No shader math is translated.
"""
from pathlib import Path
import hashlib
import json
import re

HERE = Path(__file__).resolve().parent

def sha(data):
    return hashlib.sha256(data).hexdigest()

def read_native(path):
    data = path.read_bytes()
    try:
        return data.decode("utf-8").replace("\r\n", "\n")
    except UnicodeDecodeError:
        # The matched MathConstants source contains a Windows-1252 apostrophe
        # in a comment. Original bytes remain unchanged in original/.
        return data.decode("cp1252").replace("\r\n", "\n")

def function(source, signature):
    start = source.index(signature)
    opening = source.index("{", start)
    level = 1
    end = opening + 1
    while level:
        level += (source[end] == "{") - (source[end] == "}")
        end += 1
    return start, end

def generate():
    manifest_path = HERE / "source_manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    for source in manifest["sources"]:
        assert sha((HERE / source["vendored_path"]).read_bytes()) == source["sha256"], source["vendored_path"]
    segments = []
    records = []
    def add(filename, label=None, signature=None, bounds=None):
        path = "original/" + filename
        source = read_native(HERE / path)
        record = {"vendored_path": path, "label": label or filename}
        if signature is None and bounds is None:
            segment = re.sub(r'^\s*#include[^\n]*\n', '', source, flags=re.M)
            record["kind"] = "whole_without_includes"
        else:
            start, end = bounds if bounds is not None else function(source, signature)
            segment = source[start:end]
            record.update(kind="excerpt", start=start, end=end)
        record["segment_sha256"] = sha(segment.encode())
        records.append(record)
        segments.append("// Native source: " + filename + "\n" + segment + "\n")

    add("MathConstants.hlsli")
    add("BxDFConfig.hlsli")
    add("LobeType.hlsli")
    add("MaterialData.hlsli")
    add("MathHelpers.hlsli", "sample_disk_concentric", "float2 sample_disk_concentric(float2 u)")
    add("MathHelpers.hlsli", "sample_cosine_hemisphere_concentric", "float3 sample_cosine_hemisphere_concentric(float2 u, out float pdf)")
    add("ColorHelpers.hlsli", "luminance", "inline float luminance(float3 rgb)")
    ibsdf = read_native(HERE / "original/IBSDF.hlsli")
    delta_start = ibsdf.index("static const uint       cMaxDeltaLobes")
    delta_end = ibsdf.index("};", ibsdf.index("struct DeltaLobe")) + 2
    add("IBSDF.hlsli", "DeltaLobe and cMaxDeltaLobes", bounds=(delta_start, delta_end))
    add("Fresnel.hlsli")
    add("Microfacet.hlsli")
    # The model only reads these fields in its ShadingData overload. The actual
    # local directions and native frame are supplied by the caller unchanged.
    segments.append("struct ShadingData { MaterialHeader mtl; float3 N; float3 V; };\n")
    add("BxDF.hlsli")
    body = "\n".join(segments)
    # HLSL permits mutable `this` by default; Slang requires this annotation.
    # Add it only to signatures, retaining every mathematical body unchanged.
    mutating_methods = ("setAlphaThreshold", "setNestedPriority", "setActiveLobes",
                        "setThinSurface", "setPSDExclude", "setPSDDominantDeltaLobeP1",
                        "SetEta", "SetRoughness", "__init")
    adaptation_pattern = r'^(\s*)void(\s+)(?:' + '|'.join(mutating_methods) + r')\('
    def mutable_signature(match):
        return match[1] + "CRTXPT_GI_MUTATING " + match[0][len(match[1]):]
    body, mutating_count = re.subn(adaptation_pattern, mutable_signature, body, flags=re.M)
    # Scope all native preprocessor symbols to this include as well. Native
    # types/functions/constants are already isolated inside the namespace.
    macros = sorted(set(re.findall(r'^\s*#\s*define\s+(\w+)', body, re.M)) | {
        "RTXPT_LP_TYPES_USE_16BIT_PRECISION", "RTXPT_DIFFUSE_SPECULAR_SPLIT",
        "DiffuseBrdf", "SpecularMaskingFunction"})
    wrappers = (HERE / "bridge.hlsli").read_text(encoding="utf-8")
    source = """// Generated by generate_literal.py; do not edit the native function bodies.
// Provenance and original NVIDIA license: source_manifest.json, LICENSE.txt.
#ifndef CORONA_RTXPT_GI_STANDARD_BSDF_LITERAL
#define CORONA_RTXPT_GI_STANDARD_BSDF_LITERAL
#define RTXPT_LP_TYPES_USE_16BIT_PRECISION 0
#define RTXPT_DIFFUSE_SPECULAR_SPLIT 1
#define DiffuseBrdf DiffuseBrdfFrostbite
#define SpecularMaskingFunction SpecularMaskingFunctionSmithGGXCorrelated
#ifdef __SLANG__
#define CRTXPT_GI_MUTATING [mutating]
#else
#define CRTXPT_GI_MUTATING
#endif
namespace crtxpt_gi_native {
typedef float lpfloat;
typedef float2 lpfloat2;
typedef float3 lpfloat3;
typedef float4 lpfloat4;
""" + body + "\n} // namespace crtxpt_gi_native\n" + wrappers
    source += "\n" + "\n".join("#undef " + macro for macro in macros) + "\n#undef CRTXPT_GI_MUTATING\n#endif\n"
    (HERE / "standard_bsdf.slangh").write_text(source, encoding="utf-8", newline="\n")
    chunks = [source[start:start+12000] for start in range(0, len(source), 12000)]
    literal = """// Generated by generate_literal.py; native notices are retained below.
#pragma once
#include <string>
#include <string_view>
namespace vision::rtxpt_gi::native {
// Keep individual tokens below MSVC's string-literal size limit. Concatenate
// on the host once when the typed bridge registers its content-addressed file.
inline constexpr std::string_view LiteralSourceParts[] = {
""" + "\n".join('R"CRTXPTGI(' + chunk + ')CRTXPTGI",' for chunk in chunks) + """
};
[[nodiscard]] inline std::string literal_source() {
    std::string source;
    source.reserve(""" + str(len(source.encode())) + """);
    for (std::string_view part : LiteralSourceParts) source.append(part);
    return source;
}
} // namespace vision::rtxpt_gi::native
"""
    (HERE / "literal.h").write_text(literal, encoding="utf-8", newline="\n")
    manifest["segments"] = records
    manifest["signature_adaptations"] = {"reason": "Slang requires explicit mutable this; original HLSL permits it implicitly",
                                         "marker": "CRTXPT_GI_MUTATING ", "methods": list(mutating_methods),
                                         "count_including_inactive_preprocessor_branches": mutating_count}
    manifest["generated"] = {"standard_bsdf.slangh": sha(source.encode()), "literal.h": sha(literal.encode())}
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps({"native_segments": len(records), "literal_bytes": len(source.encode()), "sha256": sha(source.encode())}))

if __name__ == "__main__":
    generate()
